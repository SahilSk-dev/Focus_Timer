const LANG_KEY = 'st_lang';
let LANG = 'en';
try { LANG = localStorage.getItem(LANG_KEY) || 'en'; } catch (e) {}

function t(key, params) {
  let s = (dict[LANG] && dict[LANG][key] !== undefined) ? dict[LANG][key] : (dict.en[key] !== undefined ? dict.en[key] : key);
  if (params) {
    Object.keys(params).forEach(k => { s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), String(params[k])); });
  }
  return s;
}

function setLang(l) {
  LANG = (l === 'bn') ? 'bn' : 'en';
  try { localStorage.setItem(LANG_KEY, LANG); } catch (e) {}
  applyLang();
}

function applyLang() {
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.getAttribute('data-i18n-title'))); });
  const enBtn = document.getElementById('langEn');
  const bnBtn = document.getElementById('langBn');
  if (enBtn) enBtn.classList.toggle('active', LANG === 'en');
  if (bnBtn) bnBtn.classList.toggle('active', LANG === 'bn');
  window.dispatchEvent(new CustomEvent('st:langchange'));
}

export { t, setLang, applyLang, LANG };
